import type { Texture } from 'pixi.js';
import { VIEW } from '../config/world';
import type { BackgroundKey, PropKey } from '../world/Room';
import type { TileRole } from '../world/tiles';
import type { CharacterArt } from './Animation';
import { paintSky, paintSkyline } from './procedural/backgrounds';
import { paint, TILE_SIZE } from './procedural/canvas';
import { buildHeroArt } from './procedural/hero';
import { PROP_PAINTERS, PROP_SIZES } from './procedural/props';
import { TILE_PAINTERS } from './procedural/tiles';

/**
 * Canvas-drawn stand-ins for every packed asset, using the project palette. The game
 * must be fully playable with an empty `public/assets/` folder: packed art is an
 * upgrade, never a requirement. Each texture is generated once, lazily.
 */
export class ProceduralArt {
  private readonly textures = new Map<string, Texture>();
  private readonly tiles = new Map<TileRole, Texture>();
  private readonly props = new Map<PropKey, Texture>();
  private readonly backgrounds = new Map<BackgroundKey, Texture>();
  readonly hero: CharacterArt;

  constructor() {
    const hero = buildHeroArt();
    this.hero = hero.art;
    this.textures.set(hero.art.textureKey, hero.texture);
  }

  /** Resolves a logical texture key generated by this provider (hero sheet, etc.). */
  texture(key: string): Texture | null {
    return this.textures.get(key) ?? null;
  }

  tile(role: TileRole): Texture {
    const cached = this.tiles.get(role);
    if (cached) return cached;
    const texture = paint(TILE_SIZE, TILE_SIZE, TILE_PAINTERS[role]);
    this.tiles.set(role, texture);
    return texture;
  }

  prop(key: PropKey): Texture {
    const cached = this.props.get(key);
    if (cached) return cached;
    const size = PROP_SIZES[key];
    const texture = paint(size.w, size.h, PROP_PAINTERS[key]);
    this.props.set(key, texture);
    return texture;
  }

  background(key: BackgroundKey): Texture {
    const cached = this.backgrounds.get(key);
    if (cached) return cached;
    const texture = paint(VIEW.width, VIEW.height, (ctx) => {
      if (key === 'far') paintSky(ctx, VIEW.width, VIEW.height);
      else paintSkyline(ctx, VIEW.width, VIEW.height);
    });
    this.backgrounds.set(key, texture);
    return texture;
  }
}
